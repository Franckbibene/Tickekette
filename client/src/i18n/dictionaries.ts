export const DICTIONARIES: Record<Lang, Record<TranslationKey, string>> = { fr, en };

export function translate(lang: Lang, key: TranslationKey, vars: Record<string, string | number> = {}): string {
  return DICTIONARIES[lang][key].replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match));
}
